use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};

use ksni::blocking::TrayMethods;

#[derive(Clone, PartialEq)]
pub struct PluginEntry {
    pub name: String,
    pub node_id: u32,
    pub has_ui: bool,
}

/// A tray menu action the main thread carries out (see
/// `AppController::poll_events`).
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum TrayAction {
    AddPlugin,
    Rules,
    Preferences,
    ToggleRules,
    ToggleExclusive,
}

#[derive(Clone)]
pub struct TrayState {
    pub show_requested: Arc<AtomicBool>,
    pub hide_requested: Arc<AtomicBool>,
    pub quit_requested: Arc<AtomicBool>,
    pub window_visible: Arc<AtomicBool>,
    pub plugins: Arc<Mutex<Vec<PluginEntry>>>,
    pub open_plugin_ui: Arc<Mutex<Option<u32>>>,
    /// Mirrors of the patchbay switches, shown as check marks.
    pub rules_enabled: Arc<AtomicBool>,
    pub exclusive: Arc<AtomicBool>,
    pub actions: Arc<Mutex<Vec<TrayAction>>>,
    handle: Arc<Mutex<Option<ksni::blocking::Handle<ZestBayTray>>>>,
}

impl TrayState {
    pub fn new() -> Self {
        Self {
            show_requested: Arc::new(AtomicBool::new(false)),
            hide_requested: Arc::new(AtomicBool::new(false)),
            quit_requested: Arc::new(AtomicBool::new(false)),
            window_visible: Arc::new(AtomicBool::new(true)),
            plugins: Arc::new(Mutex::new(Vec::new())),
            open_plugin_ui: Arc::new(Mutex::new(None)),
            rules_enabled: Arc::new(AtomicBool::new(true)),
            exclusive: Arc::new(AtomicBool::new(true)),
            actions: Arc::new(Mutex::new(Vec::new())),
            handle: Arc::new(Mutex::new(None)),
        }
    }

    /// Tell the tray host the menu changed. The host caches the menu, so
    /// without this new plugins, labels and check marks never show up.
    /// Call from the main thread, never from a tray callback.
    pub fn refresh(&self) {
        let handle = self.handle.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(h) = handle.as_ref() {
            h.update(|_| {});
        }
    }

    pub fn take_actions(&self) -> Vec<TrayAction> {
        std::mem::take(&mut *self.actions.lock().unwrap_or_else(|e| e.into_inner()))
    }

    fn push_action(&self, action: TrayAction) {
        log::info!("Tray: {:?}", action);
        self.actions.lock().unwrap_or_else(|e| e.into_inner()).push(action);
    }
}

/// The tray mark as raw ARGB32 at several sizes (the host picks the best
/// fit), generated by images/make-icons.py.
const TRAY_PIXMAPS: [(i32, &[u8]); 3] = [
    (22, include_bytes!("../images/zesttray-22.argb")),
    (32, include_bytes!("../images/zesttray-32.argb")),
    (64, include_bytes!("../images/zesttray-64.argb")),
];
const _: () = {
    let mut i = 0;
    while i < TRAY_PIXMAPS.len() {
        let (size, data) = TRAY_PIXMAPS[i];
        assert!(data.len() == (size * size * 4) as usize);
        i += 1;
    }
};

struct ZestBayTray {
    state: TrayState,
    icon_theme_path: String,
}

impl ksni::Tray for ZestBayTray {
    fn id(&self) -> String {
        "zestbay".into()
    }

    fn icon_theme_path(&self) -> String {
        self.icon_theme_path.clone()
    }

    /// No theme name: a theme lookup can resolve to an older installed
    /// icon (or none, inside a Flatpak), so the tray always gets the
    /// embedded pixmaps below, which match this build.
    fn icon_name(&self) -> String {
        String::new()
    }

    fn icon_pixmap(&self) -> Vec<ksni::Icon> {
        TRAY_PIXMAPS
            .iter()
            .map(|&(size, data)| ksni::Icon {
                width: size,
                height: size,
                data: data.to_vec(),
            })
            .collect()
    }

    fn title(&self) -> String {
        "ZestBay".into()
    }

    fn category(&self) -> ksni::Category {
        ksni::Category::ApplicationStatus
    }

    fn activate(&mut self, _x: i32, _y: i32) {
        let currently_visible = self.state.window_visible.load(Ordering::Acquire);
        log::info!("Tray: activate (left-click), currently_visible={currently_visible}");
        if currently_visible {
            self.state.window_visible.store(false, Ordering::Release);
            self.state.hide_requested.store(true, Ordering::Release);
        } else {
            self.state.window_visible.store(true, Ordering::Release);
            self.state.show_requested.store(true, Ordering::Release);
        }
    }

    // Show/Hide · Plugin UIs ▸ · — · Add plugin… · Patchbay rules… ·
    // [x] Rules enabled · [x] Exclusive mode · — · Preferences… · Quit.
    // Rendered by the desktop, so it follows the system theme.
    fn menu(&self) -> Vec<ksni::MenuItem<Self>> {
        use ksni::menu::*;

        fn action(label: &str, icon: &str, a: TrayAction) -> ksni::MenuItem<ZestBayTray> {
            StandardItem {
                label: label.into(),
                icon_name: icon.into(),
                activate: Box::new(move |tray: &mut ZestBayTray| tray.state.push_action(a)),
                ..Default::default()
            }
            .into()
        }

        let visible = self.state.window_visible.load(Ordering::Acquire);
        let rules_on = self.state.rules_enabled.load(Ordering::Acquire);
        let exclusive = self.state.exclusive.load(Ordering::Acquire);
        let mut items: Vec<ksni::MenuItem<Self>> = Vec::new();

        items.push(
            StandardItem {
                label: if visible { "Hide ZestBay" } else { "Show ZestBay" }.into(),
                icon_name: if visible { "window-minimize" } else { "window-restore" }.into(),
                activate: Box::new(|tray: &mut Self| tray.activate(0, 0)),
                ..Default::default()
            }
            .into(),
        );

        let plugins = self
            .state
            .plugins
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .clone();
        let mut plugin_items: Vec<ksni::MenuItem<Self>> = plugins
            .iter()
            .map(|plugin| {
                let node_id = plugin.node_id;
                StandardItem {
                    label: if plugin.has_ui {
                        plugin.name.clone()
                    } else {
                        format!("{} (no UI)", plugin.name)
                    },
                    enabled: plugin.has_ui,
                    activate: Box::new(move |tray: &mut ZestBayTray| {
                        log::info!("Tray: open plugin UI for node_id={}", node_id);
                        if let Ok(mut req) = tray.state.open_plugin_ui.lock() {
                            *req = Some(node_id);
                        }
                    }),
                    ..Default::default()
                }
                .into()
            })
            .collect();
        if plugin_items.is_empty() {
            plugin_items.push(
                StandardItem {
                    label: "No active plugins".into(),
                    enabled: false,
                    ..Default::default()
                }
                .into(),
            );
        }
        items.push(
            SubMenu {
                label: "Plugin UIs".into(),
                icon_name: "plugins".into(),
                submenu: plugin_items,
                ..Default::default()
            }
            .into(),
        );

        items.push(ksni::MenuItem::Separator);
        items.push(action("Add plugin\u{2026}", "list-add", TrayAction::AddPlugin));
        items.push(action("Patchbay rules\u{2026}", "view-filter", TrayAction::Rules));
        items.push(
            CheckmarkItem {
                label: "Rules enabled".into(),
                checked: rules_on,
                activate: Box::new(|tray: &mut Self| tray.state.push_action(TrayAction::ToggleRules)),
                ..Default::default()
            }
            .into(),
        );
        items.push(
            CheckmarkItem {
                label: "Exclusive mode".into(),
                checked: exclusive,
                enabled: rules_on,
                activate: Box::new(|tray: &mut Self| tray.state.push_action(TrayAction::ToggleExclusive)),
                ..Default::default()
            }
            .into(),
        );

        items.push(ksni::MenuItem::Separator);
        items.push(action("Preferences\u{2026}", "configure", TrayAction::Preferences));
        items.push(
            StandardItem {
                label: "Quit".into(),
                icon_name: "application-exit".into(),
                activate: Box::new(|tray: &mut Self| {
                    log::info!("Tray: Quit menu item clicked");
                    tray.state.quit_requested.store(true, Ordering::Release);
                }),
                ..Default::default()
            }
            .into(),
        );

        items
    }
}

pub fn spawn_tray() -> TrayState {
    let state = TrayState::new();
    let tray_state = state.clone();

    let icon_theme_path = {
        let mut path = std::env::current_exe()
            .ok()
            .and_then(|p| p.parent().map(|d| d.join("icons")))
            .unwrap_or_default();
        if !path.exists() {
            path = std::path::PathBuf::from("icons");
        }
        if path.exists() {
            path.to_string_lossy().into_owned()
        } else {
            String::new()
        }
    };

    std::thread::Builder::new()
        .name("zestbay-tray".into())
        .spawn(move || {
            let handle_slot = tray_state.handle.clone();
            let tray = ZestBayTray {
                state: tray_state,
                icon_theme_path,
            };
            match tray.spawn() {
                Ok(handle) => {
                    *handle_slot.lock().unwrap_or_else(|e| e.into_inner()) = Some(handle);
                    loop {
                        std::thread::park();
                    }
                }
                Err(e) => {
                    log::warn!("Failed to create system tray icon: {}", e);
                    log::warn!("The application will still run but won't have a tray icon.");
                }
            }
        })
        .expect("Failed to spawn tray thread");

    state
}
